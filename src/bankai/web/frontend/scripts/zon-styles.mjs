// Writes src/zon.css: @zonsh/ui's stylesheet, trimmed for bankai. Run after updating the package
// (`npm run zon:styles`). Three things differ from `@import "@zonsh/ui/styles.css"`:
//  - only the core, and React Flow's base styles from the graph part: the parts bankai uses none of (prose and
//    code blocks, illustration, pdf, editor, ai, zon's graph look, brand) are left out: their selectors were
//    matched against every element at every style recalculation (code blocks alone: 400,000 tries a page);
//  - Tailwind scans only the components bankai imports (the package's `sources/<component>.css`, each naming
//    the files its component is built from), not all of them: button-group's :nth-child(… of …) selectors,
//    generated though nothing used it, were matched against every element;
//  - the Licht faces are not imported here but by main.tsx (`import 'licht/all.css'`): inlined by Tailwind's
//    @import, the faces' relative `./files/*.woff2` URLs were not rebased, and no font reached the build.
//    The core's fonts.css (the size-matched fallbacks) is copied to src/zon-fonts.css without that import.
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dist = join(root, 'node_modules/@zonsh/ui/dist');
const from = relative(join(root, 'src'), join(dist, 'styles'));

// The components bankai imports, by the names it imports.
const used = new Set();
const sources = [];
const walk = (dir) => {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) walk(path);
    else if (/\.(tsx?|jsx?)$/.test(entry.name)) sources.push(path);
  }
};
walk(join(root, 'src'));
const exportsOf = new Map(); // component file -> its exported names
for (const file of readdirSync(join(dist, 'components')).filter((name) => name.endsWith('.d.ts'))) {
  const text = readFileSync(join(dist, 'components', file), 'utf8');
  const names = [...text.matchAll(/export (?:declare )?(?:function|const|class|type|interface) (\w+)/g)].map((m) => m[1]);
  for (const m of text.matchAll(/export \{([^}]*)\}/g)) names.push(...m[1].split(',').map((n) => n.trim().replace(/^type /, '').split(' as ').pop()));
  exportsOf.set(file.replace('.d.ts', ''), new Set(names.filter(Boolean)));
}
for (const source of sources) {
  const text = readFileSync(source, 'utf8');
  for (const m of text.matchAll(/import \{([^}]*)\} from '@zonsh\/ui(?:\/([\w-]+))?'/g)) {
    if (m[2]) { used.add(m[2]); continue; }
    for (const raw of m[1].split(',')) {
      const name = raw.trim().replace(/^type /, '').split(' as ')[0];
      for (const [component, names] of exportsOf) if (names.has(name)) used.add(component);
    }
  }
}
const scanned = [...used].filter((c) => existsSync(join(dist, 'sources', c + '.css'))).sort();
// Their @source lines, rebased to src/ (an @import cannot follow the core's rules).
const files = new Set();
for (const c of scanned) {
  for (const m of readFileSync(join(dist, 'sources', c + '.css'), 'utf8').matchAll(/^@source "\.\.\/([\w/.-]+)";/gm)) files.add(m[1]);
}

// The core, its fonts.css swapped for the copy without Licht.
const fonts = readFileSync(join(dist, 'styles/fonts.css'), 'utf8').replace(/^@import "licht\/all\.css";\n/m, '');
writeFileSync(
  join(root, 'src/zon-fonts.css'),
  `/* Generated by scripts/zon-styles.mjs from @zonsh/ui's styles/fonts.css, less its Licht import: do not edit. */\n` + fonts,
);
let core = readFileSync(join(dist, 'styles/core.css'), 'utf8')
  .replace(/^@import "\.\/([\w/.-]+)";/gm, (line, path) => (path === 'fonts.css' ? '@import "./zon-fonts.css";' : `@import "${from}/${path}";`));
// React Flow's base styles (the relation graphs: CollectionGraph, MangaGraph use @xyflow/react itself, not zon's
// Graph, so not graph.css's look). 0.6.0 moved them out of the core into the graph part; left out with it, the
// graphs drew their nodes unplaced. Among the imports: an @import after the core's rules would be dropped.
const imports = [...core.matchAll(/^@import .*;$/gm)];
const last = imports[imports.length - 1];
core = core.slice(0, last.index + last[0].length) + `\n@import "${from}/parts/react-flow.css";` + core.slice(last.index + last[0].length);
const out =
  `/* Generated by scripts/zon-styles.mjs from @zonsh/ui's styles/core.css: do not edit, run \`npm run zon:styles\`. */\n` +
  core +
  '\n/* The components bankai imports, for Tailwind to scan. */\n' +
  [...files].sort().map((f) => `@source "${relative(join(root, 'src'), dist)}/${f}";`).join('\n') +
  '\n';
writeFileSync(join(root, 'src/zon.css'), out.replace(/\n{3,}/g, '\n\n'));
console.log(`src/zon.css: core + ${scanned.length} components, ${files.size} files scanned`);
