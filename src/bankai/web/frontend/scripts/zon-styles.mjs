// Writes src/zon.css: @zonsh/ui's stylesheet entry, trimmed for bankai. Run after updating the package
// (`npm run zon:styles`). Two things differ from `@import "@zonsh/ui/styles.css"`:
//  - the parts bankai uses none of (foundations: prose and code blocks, brand, editorial, isometric, pdf,
//    ai, graph) are left out: their selectors were matched against every element at every style
//    recalculation (code blocks alone: 400,000 tries a page);
//  - Tailwind scans only the components bankai imports and what they import, not all 102: button-group's
//    :nth-child(… of …) selectors, generated though nothing used it, were matched against every element.
import { readFileSync, writeFileSync, readdirSync } from 'node:fs';
import { dirname, join, relative } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const dist = join(root, 'node_modules/@zonsh/ui/dist');
const DROPPED = ['foundations', 'brand', 'editorial', 'isometric', 'pdf', 'ai', 'graph'];

// The components bankai imports, by the names it imports, and the component files they import in turn.
const used = new Set();
const sources = [];
const walk = (dir) => {
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name);
    if (entry.isDirectory()) walk(path);
    else if (/\.(tsx?|jsx?)$/.test(entry.name)) sources.push(path);
  }
};
walk(join(root, 'src'));
const exportsOf = new Map(); // component file -> its exported names
for (const file of readdirSync(join(dist, 'components')).filter((name) => name.endsWith('.d.ts'))) {
  const text = readFileSync(join(dist, 'components', file), 'utf8');
  const names = [...text.matchAll(/export (?:declare )?(?:function|const|class|type|interface) (\w+)/g)].map((m) => m[1]);
  for (const m of text.matchAll(/export \{([^}]*)\}/g)) names.push(...m[1].split(',').map((n) => n.trim().replace(/^type /, '').split(' as ').pop()));
  exportsOf.set(file.replace('.d.ts', ''), new Set(names.filter(Boolean)));
}
for (const source of sources) {
  const text = readFileSync(source, 'utf8');
  for (const m of text.matchAll(/import \{([^}]*)\} from '@zonsh\/ui(?:\/([\w-]+))?'/g)) {
    if (m[2]) { used.add(m[2]); continue; }
    for (const raw of m[1].split(',')) {
      const name = raw.trim().replace(/^type /, '').split(' as ')[0];
      for (const [component, names] of exportsOf) if (names.has(name)) used.add(component);
    }
  }
}
const queue = [...used];
while (queue.length) {
  const component = queue.pop();
  let text = '';
  try { text = readFileSync(join(dist, 'components', component + '.js'), 'utf8'); } catch { continue; }
  for (const m of text.matchAll(/from "\.\/([\w-]+)\.js"/g)) if (!used.has(m[1])) { used.add(m[1]); queue.push(m[1]); }
}

const entry = readFileSync(join(dist, 'styles/index.css'), 'utf8');
const from = relative(join(root, 'src'), join(dist, 'styles'));
let out = entry
  .replace(/^@source "\.\.\/";\n/m, '')
  .replace(/^@source "\.\.\/components";\n/m, [...used].sort().map((c) => `@source "${from}/../components/${c}.js";`).join('\n') + '\n')
  .replace(/^@source "\.\.\/lib";/m, `@source "${from}/../lib";`)
  .replace(/^@import "\.\/([\w/.-]+)";/gm, (line, path) => (DROPPED.some((part) => path === `parts/${part}.css`) ? '' : `@import "${from}/${path}";`));
out = `/* Generated by scripts/zon-styles.mjs from @zonsh/ui's styles/index.css: do not edit, run \`npm run zon:styles\`. */\n` + out;
writeFileSync(join(root, 'src/zon.css'), out.replace(/\n{3,}/g, '\n\n'));
console.log(`src/zon.css: ${used.size} components scanned, ${DROPPED.length} parts left out`);
